<#
.SYNOPSIS
    Installs a small "OpenTools-dev" bundle that loads OpenTools straight from this
    checkout and turns on the dev bridge. Restart 3ds Max afterwards.

.NOTES
    Do not install the release OpenTools.bundle at the same time; the first one
    to start wins and the other does nothing.
    Remove with dev\uninstall_dev.ps1.
#>
param(
    [string]$PluginsDir = (Join-Path $env:APPDATA "Autodesk\ApplicationPlugins")
)

$ErrorActionPreference = "Stop"
$repo = Split-Path -Parent $PSScriptRoot
$pythonRoot = Join-Path $repo "OpenTools.bundle\Contents\python"
if (-not (Test-Path (Join-Path $pythonRoot "opentools\__init__.py"))) {
    throw "Cannot find the OpenTools package under $pythonRoot"
}
if ($repo.Contains("'")) {
    throw "The repository path must not contain an apostrophe: $repo"
}

$target = Join-Path $PluginsDir "OpenTools-dev.bundle"
$scripts = Join-Path $target "Contents\scripts"
New-Item -ItemType Directory -Force -Path $scripts | Out-Null

$pythonFwd = $pythonRoot.Replace("\", "/")
$repoFwd = $repo.Replace("\", "/")

$packageContents = @"
<?xml version="1.0" encoding="utf-8"?>
<ApplicationPackage
    SchemaVersion="1.0"
    AutodeskProduct="3ds Max"
    ProductType="Application"
    Name="OpenTools (dev)"
    Description="Loads OpenTools from a development checkout: $repo"
    AppVersion="0.0.0"
    ProductCode="{2A7F4E61-9C03-4B58-B1D2-7E60F8A34C9D}"
    UpgradeCode="{D93C1B07-6E4A-4F21-A8B5-3C9E072F61A4}">
    <CompanyDetails Name="OpenTools contributors" />
    <RuntimeRequirements OS="Win64" Platform="3ds Max" SeriesMin="2025" SeriesMax="2099" />
    <Components Description="post-start-up scripts parts">
        <RuntimeRequirements OS="Win64" Platform="3ds Max" SeriesMin="2025" SeriesMax="2099" />
        <ComponentEntry AppName="OpenTools-dev" Version="0.0.0" ModuleName="./Contents/scripts/opentools_dev_startup.ms" />
    </Components>
</ApplicationPackage>
"@

$startup = @"
-- Generated by dev/install_dev.ps1. Loads OpenTools from $repo with the dev bridge on.
python.Execute ( \
    "import sys\n" + \
    "root = r'$pythonFwd'\n" + \
    "if root not in sys.path: sys.path.insert(0, root)\n" + \
    "import opentools.bootstrap\n" + \
    "opentools.bootstrap.start(dev_root=r'$repoFwd')\n" )
"@

$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText((Join-Path $target "PackageContents.xml"), $packageContents, $utf8)
[System.IO.File]::WriteAllText((Join-Path $scripts "opentools_dev_startup.ms"), $startup, $utf8)

Write-Host "Installed $target"
Write-Host "Loads OpenTools from: $repo"
Write-Host "Restart 3ds Max to load it."
